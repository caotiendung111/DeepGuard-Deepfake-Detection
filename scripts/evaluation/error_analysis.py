"""
DeepGuard — Error Analysis Script
Analyzes predictions.csv from evaluate.py to extract top False Positives and False Negatives.
Copies images to an error directory for manual review.

Usage:
    python scripts/evaluation/error_analysis.py --preds reports/evaluation/predictions.csv --top-k 20
"""
import argparse
import shutil
from pathlib import Path

import pandas as pd
from loguru import logger
from rich.console import Console
from rich.table import Table

console = Console()

def parse_args():
    parser = argparse.ArgumentParser(description="DeepGuard Error Analysis")
    parser.add_argument("--preds", type=str, default="reports/evaluation/predictions.csv",
                        help="Path to predictions.csv generated by evaluate.py")
    parser.add_argument("--top-k", type=int, default=20,
                        help="Number of top FP/FN to extract")
    parser.add_argument("--output-dir", type=str, default="reports/evaluation/errors")
    return parser.parse_args()

def export_images(df: pd.DataFrame, output_dir: Path, prefix: str):
    """Copy images to output directory with descriptive names."""
    for idx, row in df.iterrows():
        src_path = Path(row['filepath'])
        if not src_path.exists():
            continue
            
        prob = row['probability']
        # e.g. FP_01_prob0.99_vid001_frame01.jpg
        dst_name = f"{prefix}_{idx+1:02d}_prob{prob:.4f}_{src_path.name}"
        dst_path = output_dir / dst_name
        
        shutil.copy2(src_path, dst_path)

def main():
    args = parse_args()
    
    preds_path = Path(args.preds)
    if not preds_path.exists():
        logger.error(f"Predictions file not found: {preds_path}. Run evaluate.py first.")
        return
        
    df = pd.read_csv(preds_path)
    
    # False Positives: True Label = 0 (Real), Prediction = 1 (Fake) -> High probability
    fp_df = df[(df['label'] == 0) & (df['prediction'] == 1)]
    # Sort descending by probability (most confident wrong fakes)
    fp_top = fp_df.sort_values(by='probability', ascending=False).head(args.top_k).reset_index(drop=True)
    
    # False Negatives: True Label = 1 (Fake), Prediction = 0 (Real) -> Low probability
    fn_df = df[(df['label'] == 1) & (df['prediction'] == 0)]
    # Sort ascending by probability (most confident wrong reals)
    fn_top = fn_df.sort_values(by='probability', ascending=True).head(args.top_k).reset_index(drop=True)
    
    # --- Display ---
    console.print(f"\n[bold red]Top {len(fp_top)} False Positives (Real labeled as Fake)[/bold red]")
    fp_table = Table(show_header=True, header_style="bold red")
    fp_table.add_column("Rank", style="dim", width=6)
    fp_table.add_column("File", style="cyan")
    fp_table.add_column("Probability", justify="right", style="magenta")
    for idx, row in fp_top.iterrows():
        fp_table.add_row(str(idx+1), Path(row['filepath']).name, f"{row['probability']:.4f}")
    console.print(fp_table)
    
    console.print(f"\n[bold yellow]Top {len(fn_top)} False Negatives (Fake labeled as Real)[/bold yellow]")
    fn_table = Table(show_header=True, header_style="bold yellow")
    fn_table.add_column("Rank", style="dim", width=6)
    fn_table.add_column("File", style="cyan")
    fn_table.add_column("Probability", justify="right", style="magenta")
    for idx, row in fn_top.iterrows():
        fn_table.add_row(str(idx+1), Path(row['filepath']).name, f"{row['probability']:.4f}")
    console.print(fn_table)
    
    # --- Export ---
    out_dir = Path(args.output_dir)
    fp_dir = out_dir / "false_positives"
    fn_dir = out_dir / "false_negatives"
    
    fp_dir.mkdir(parents=True, exist_ok=True)
    fn_dir.mkdir(parents=True, exist_ok=True)
    
    logger.info(f"Exporting top {args.top_k} FP images to {fp_dir}")
    export_images(fp_top, fp_dir, "FP")
    
    logger.info(f"Exporting top {args.top_k} FN images to {fn_dir}")
    export_images(fn_top, fn_dir, "FN")
    
    # Save CSVs
    fp_top.to_csv(out_dir / "top_false_positives.csv", index=False)
    fn_top.to_csv(out_dir / "top_false_negatives.csv", index=False)
    logger.success(f"Analysis complete. Results saved in {out_dir}")

if __name__ == "__main__":
    main()
